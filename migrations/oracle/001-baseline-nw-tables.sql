);
CREATE INDEX IX_NW_RB_ITEM ON NW_ROLLBACK(ITEM_ID);
CREATE INDEX IX_NW_RB_ORIGIN_BOX ON NW_ROLLBACK(ORIGIN_BOX_ID);

-- 12. NW_AUDIT_LOG (Trilha de Auditoria com Correlation ID)
CREATE TABLE NW_AUDIT_LOG (
    ID VARCHAR2(36 CHAR) NOT NULL,
    CORRELATION_ID VARCHAR2(50 CHAR) NOT NULL,
    ACTOR VARCHAR2(100 CHAR) NOT NULL,
    ACTION VARCHAR2(100 CHAR) NOT NULL,
    ENTITY_TYPE VARCHAR2(50 CHAR) NOT NULL,
    ENTITY_ID VARCHAR2(50 CHAR) NOT NULL,
    BEFORE_STATE CLOB,
    AFTER_STATE CLOB,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_NW_AUDIT_LOG PRIMARY KEY (ID)
);
CREATE INDEX IX_NW_AUDIT_CORR ON NW_AUDIT_LOG(CORRELATION_ID);
CREATE INDEX IX_NW_AUDIT_ENTITY ON NW_AUDIT_LOG(ENTITY_TYPE, ENTITY_ID);
CREATE INDEX IX_NW_AUDIT_ACTION ON NW_AUDIT_LOG(ACTION);
