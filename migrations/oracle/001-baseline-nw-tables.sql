-- 11. NW_ROLLBACK (Trilha de Reversão para Rede de Origem)
CREATE TABLE NW_ROLLBACK (
    ID VARCHAR2(36 CHAR) NOT NULL,
    ITEM_ID VARCHAR2(36 CHAR) NOT NULL,
    ORIGIN_BOX_ID VARCHAR2(100 CHAR) NOT NULL,
    REASON VARCHAR2(500 CHAR) NOT NULL,
    STATUS VARCHAR2(30 CHAR) DEFAULT 'ROLLBACK_REQUESTED' NOT NULL,
    REQUESTED_BY VARCHAR2(100 CHAR) NOT NULL,
    REQUESTED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
